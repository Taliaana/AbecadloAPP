test('szczegółowa instrukcja, uchwyty, Shift i wklejenie źródła', async ({ page }) => {
  await begin(page)
  await page.getByText('Jak wykonać zadanie?', { exact: true }).click()
  await expect(page.getByRole('img', { name: 'Google Chrome', exact: true })).toBeVisible()
  await expect(page.locator('.research-instructions li')).toHaveCount(10)
  await expect(page.getByText('Tutaj zobaczysz zdjęcia pasujące do wyszukiwania.', { exact: true })).toBeVisible()
  await expect(page.getByText(/kliknij zdjęcie prawym przyciskiem/i)).toBeVisible()
  await expect(page.getByText('Shift – zachowaj proporcje obrazu podczas zmiany rozmiaru', { exact: false })).toBeVisible()
  await page.getByText('Jak wykonać zadanie?', { exact: true }).click()
  await pastePhoto(page, 'granit')
  const box = page.locator('[data-item="granit"] .research-image-box')
  const handle = box.locator('[data-resize-corner="se"]')
  async function drag(dx, dy, shift = false) {
    await handle.scrollIntoViewIfNeeded()
    const rect = await handle.boundingBox()
    if (shift) await page.keyboard.down('Shift')
    await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2)
    await page.mouse.down(); await page.mouse.move(rect.x + rect.width / 2 + dx, rect.y + rect.height / 2 + dy, { steps: 5 }); await page.mouse.up()
    if (shift) await page.keyboard.up('Shift')
  }
  const original = await box.boundingBox()
  await drag(-45, -10)
  const resized = await box.boundingBox()
  expect(resized.width).toBeLessThan(original.width - 30)
  expect(resized.height).toBeLessThan(original.height)
  expect(Math.abs(resized.width / resized.height - 4 / 3)).toBeGreaterThan(.05)
  await drag(-12, 0, true)
  const proportional = await box.boundingBox()
  expect(proportional.width / proportional.height).toBeCloseTo(4 / 3, 1)
  await handle.focus(); await page.keyboard.press('Shift+ArrowLeft')
  expect((await box.boundingBox()).width).toBeLessThan(proportional.width)
  // A text paste in Source must not replace the selected picture.
  await page.evaluate(() => {
    const input = document.createElement('input'); input.value = 'https://example.org/granit'; document.body.append(input); input.focus(); input.select()
  })
  await page.keyboard.press('Control+C')
  await page.locator('[data-source="granit"]').click()
  await page.keyboard.press('Control+V')
  await expect(page.locator('[data-source="granit"]')).toHaveValue('https://example.org/granit')
  const savedSize = await box.boundingBox()
  await page.reload()
  await expect(page.locator('[data-research-image="granit"]')).toBeVisible()
  await expect(page.locator('[data-source="granit"]')).toHaveValue('https://example.org/granit')
  const restored = await box.boundingBox()
  expect(restored.width).toBeCloseTo(savedSize.width, 0)
  expect(restored.height).toBeCloseTo(savedSize.height, 0)
})

test('Ctrl+V, wybrane pole, zmiana/usunięcie oraz odtworzenie zdjęć i odpowiedzi', async ({ page }) => {
  await begin(page)
  await expect(page.getByRole('button', { name: /Pokaż nauczycielowi/ })).toBeDisabled()
  await pastePhoto(page, 'bazalt')
  await expect(page.locator('[data-research-image="granit"]')).toBeHidden()
  await page.locator('[data-source="bazalt"]').fill('https://example.org/bazalt')
  const first = await page.locator('[data-research-image="bazalt"]').getAttribute('data-image-id')
  await page.locator('[data-change="bazalt"]').click()
  await copyPhoto(page, '#555555'); await page.keyboard.press('Control+V')
  await expect(page.locator('[data-research-image="bazalt"]')).not.toHaveAttribute('data-image-id', first)
  await expect(page.locator('[data-photo="bazalt"]')).toBeEnabled()
  await page.locator('[data-remove="bazalt"]').click()
  await expect(page.locator('[data-research-image="bazalt"]')).toBeHidden()
  await pastePhoto(page, 'bazalt')
  await page.reload()
  await expect(page.locator('[data-research-image="bazalt"]')).toBeVisible()
  await expect(page.locator('[data-source="bazalt"]')).toHaveValue('https://example.org/bazalt')
  await expect.poll(() => page.locator('[data-research-image="bazalt"]').evaluate(img => img.naturalWidth)).toBe(32)
  const imageCount = await page.evaluate(() => new Promise((resolve, reject) => {
    const request = indexedDB.open('pinktower-images', 1)
    request.onsuccess = () => {
      const db = request.result, count = db.transaction('images', 'readonly').objectStore('images').count()
      count.onsuccess = () => { resolve(count.result); db.close() }
      count.onerror = () => reject(count.error)
    }
    request.onerror = () => reject(request.error)
  }))
  expect(imageCount).toBe(1) // Replacements/removals do not accumulate unused Blobs.
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('abecadlo-state-v3')).students.zosia.works.find(work => work.data.kind === 'research-board'))
  expect(stored.data.entries.bazalt.imageId).toBeTruthy()
  expect(JSON.stringify(stored)).not.toContain('data:image')
  expect(stored.data.entries.granit).toBeUndefined()
  for (const viewport of [{ width: 1440, height: 900 }, { width: 1366, height: 768 }, { width: 1024, height: 768 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    expect((await page.locator('[data-photo="granit"]').boundingBox()).height).toBeGreaterThanOrEqual(44)
  }
  // Debounced edits must also flush before switching to a different route.
  await page.locator('[data-source="bazalt"]').fill('https://example.org/new')
  await page.getByRole('link', { name: 'Dom', exact: true }).click()
  await page.goto(`/#/work/${stored.id}`)
  await expect(page.locator('[data-source="bazalt"]')).toHaveValue('https://example.org/new')
  // The other profile cannot see or open this work.
  await page.goto('/#/welcome'); await chooseStudent(page, 'Lena')
  await page.goto(`/#/work/${stored.id}`)
  await expect(page.getByText('Nie znaleziono pracy.')).toBeVisible()
})

