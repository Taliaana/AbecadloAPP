async function copyPhoto(page, color = '#999999') {
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.evaluate(async fill => {
    const canvas = document.createElement('canvas'); canvas.width = 32; canvas.height = 24
    const ctx = canvas.getContext('2d'); ctx.fillStyle = fill; ctx.fillRect(0, 0, 32, 24)
    const blob = await new Promise(resolve => canvas.toBlob(resolve, 'image/png'))
    await navigator.clipboard.write([new ClipboardItem({ 'image/png': blob })])
  }, color)
}
async function pastePhoto(page, id, color) {
  await copyPhoto(page, color)
  await page.locator(`[data-photo="${id}"]`).click()
  await expect(page.locator(`[data-photo="${id}"]`)).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Control+V')
  await expect(page.locator(`[data-research-image="${id}"]`)).toBeVisible()
  await expect(page.locator(`[data-photo="${id}"]`)).toBeEnabled()
}
